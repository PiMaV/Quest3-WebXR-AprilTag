// Deterministic diagram build: docs/diagrams/*.mmd (source of truth) -> docs/diagrams.md.
//   node scripts/build-diagrams.mjs          write docs/diagrams.md
//   node scripts/build-diagrams.mjs --check  fail if docs/diagrams.md is out of date
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'docs/diagrams');
const TITLES = {
  '00-overview': ['Overview', 'All modules in context; yellow = one-time, blue = live, green = output.', 'Technical papers · [English](../paper/overview.qmd) | [Deutsch](../paper/uebersicht.qmd)'],
  '01-calibration': ['Calibration', '`solveCalibration` in `src/solver.mjs`, gates from `docs/architecture.md`.', 'Camera extrinsics and time offset · [English](../paper/01-calibration.qmd) | [Deutsch](../paper/01-kalibrierung.qmd)'],
  '02-origin-tracking': ['Origin Tracking (L-angle → XRAnchor)', '`src/anchor.mjs`, `src/anchor-audit.mjs`.', 'Technical paper · [English](../paper/02-world-origin.qmd) | [Deutsch](../paper/02-raumursprung.qmd)'],
  '03-single-tracking': ['Single Tracking', 'detection → PnP → time alignment → motion gate (`src/detector.mjs`, `src/motion-guard.mjs`).', 'Technical paper · [English](../paper/03-single-tag.qmd) | [Deutsch](../paper/03-einzelmarker.qmd)'],
  '04-multi-tracking': ['Multi Tracking (Focus-ROI)', 'Movable tags 300–349 (`src/camera.mjs`, `docs/controls.md`).', 'Technical paper · [English](../paper/04-multi-tag-focus.qmd) | [Deutsch](../paper/04-mehrmarker-fokus.qmd)'],
  '05-hand-coupling': ['Hand Coupling', '`src/hand-coupling.mjs`.', 'Technical paper · [English](../paper/05-hand-coupling.qmd) | [Deutsch](../paper/05-handkopplung.qmd)'],
  '06-prediction': ['Prediction', 'Damped Constant-Velocity 6DOF (`src/tag-predictor.mjs`).', 'Technical paper · [English](../paper/06-prediction.qmd) | [Deutsch](../paper/06-praediktion.qmd)'],
  '07-path-fusion': ['Path Fusion & Smoothing', '`src/path-smoother.mjs`.', 'Technical paper · [English](../paper/07-trajectory-correction.qmd) | [Deutsch](../paper/07-bahnkorrektur.qmd)'],
  '08-perimeter-fence': ['Perimeter Fence', '`src/perimeter-fence.mjs`.', 'Technical paper · [English](../paper/08-perimeter.qmd) | [Deutsch](../paper/08-tischkontur.qmd)'],
};
const files = readdirSync(dir).filter((f) => f.endsWith('.mmd')).sort();
let md = '<!-- GENERATED by scripts/build-diagrams.mjs from docs/diagrams/*.mmd. Do not edit. -->\n# Diagrams (Graphical Abstracts)\n\n';
md += files.map((f) => `- [${TITLES[f.slice(0, -4)]?.[0] ?? f}](#${(TITLES[f.slice(0, -4)]?.[0] ?? f).toLowerCase().replace(/[^a-z0-9 ]/g, '').replace(/ /g, '-')})`).join('\n') + '\n';
for (const f of files) {
  const [title, note, paperLink] = TITLES[f.slice(0, -4)] ?? [f, ''];
  md += `\n## ${title}\n\n${note}${paperLink ? `\n\n${paperLink}` : ''}\n\n\`\`\`mermaid\n${readFileSync(path.join(dir, f), 'utf8').trimEnd()}\n\`\`\`\n`;
}
const out = path.join(root, 'docs/diagrams.md');
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(out, 'utf8'); } catch {}
  if (cur !== md) { console.error('docs/diagrams.md is stale; run node scripts/build-diagrams.mjs'); process.exit(1); }
  console.log('diagrams up to date');
} else {
  writeFileSync(out, md);
  console.log(`wrote docs/diagrams.md (${files.length} diagrams)`);
}
